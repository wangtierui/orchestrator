def extract_orgs(text: str) -> list[str]:
    """从文本中提取规范机构全称（按出现顺序、去重）。"""
    if not text:
        return []
    out: list[str] = []
    seen: set[str] = set()
    i, n = 0, len(text)
    while i < n:
        hit = ""
        for k in _ORG_KEYS:
            if text.startswith(k, i):
                hit = k
                break
        if hit:
            canon = _ORG_ALIAS[hit]
            if canon not in seen:
                seen.add(canon)
                out.append(canon)
            i += len(hit)
        else:
            i += 1
    return out


_REBUILD_TAIL = re.compile(r"(公告\s*\d{4}\s*年\s*第?\s*\d+\s*号)\s*$")


def rebuild_multi_org_docno(doc_no: str, title: str) -> str:
    """多机关联合公告：以标题机构链重建文号前缀（仅当标题机构数严格更多时）。

    - 触发形态：文号以「公告YYYY年第N号」结尾（联合令/单一机关令不处理）。
    - 标题取「关于」之前部分作为机构链来源，避免正文/文件名噪声。
    - 例：'银行中国银行业监督管理委员会中国证券监督管理委员会中国保险监督管理委员会公告2017年第14号'
          + '国家税务总局 财政部 中国人民银行 银监会 证监会 保监会关于发布《…》的公告'
          → '国家税务总局财政部中国人民银行中国银行业监督管理委员会中国证券监督管理委员会中国保险监督管理委员会公告2017年第14号'
    """
    if not doc_no or not title:
        return doc_no
    m = _REBUILD_TAIL.search(doc_no)
    if not m:
        return doc_no
    tail = m.group(1)
    head = doc_no[: m.start()]
    # 标题机构链：仅取「关于」之前
    t = str(title).split("关于")[0]
    orgs_title = extract_orgs(t)
    if not orgs_title:
        return doc_no
    orgs_now = extract_orgs(head)
    if len(orgs_title) <= len(orgs_now):
        return doc_no  # 现有前缀机构不少于标题 → 不改动（保守）
    return "".join(orgs_title) + tail


def looks_like_doc_number(v: object) -> bool:
    """判定字符串是否具备文号形态（供缺失校验/补全触发）。"""
    if not v:
        return False
    s = str(v).strip()
    if not s or s.upper() in ("N/A", "NA", "NULL"):
        return False
    return bool(
        re.search(
            # 令号（无年份，如 国务院令第300号 / 保监会令第5号）
            r"(令\s*第?\s*[一二三四五六七八九十百\d]+\s*号"
            # 令号（年份在"令"后，如 中国银监会令2008年第1号 / 银保监会令2018年第5号）
            # 2026-09-07：补此分支，否则该类 103 条真实文号被判否而在清洗层整批置空
            r"|令\s*\d{4}\s*年\s*第?\s*[一二三四五六七八九十百\d]+\s*号"
            r"|〔\d{4}〕\s*第?\s*\d+\s*号|\[\d{4}\]\s*第?\s*\d+\s*号"
            r"|公告\s*\d{4}\s*年\s*第?\s*[一二三四五六七八九十百\d]+\s*号)",
            s,
        )
    )


