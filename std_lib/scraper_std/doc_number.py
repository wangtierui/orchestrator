def _locate_doc_span(s: str) -> str:
    """从可能含标题残渣的字符串中定位最左合法代字锚定的文号片段；未命中返回空串。"""
    m = _DAIZI_RE.search(s)
    if m:
        return m.group(0)
    # 已知机关令号优先于宽松中文前缀（避免吞入日期残渣"日"等）
    m = _LING_RE.search(s)
    if m:
        return m.group(0)
    m = _SPAN_LING.search(s)
    if m:
        return m.group(0)
    # 兜底：复用优先级正则（覆盖未列入词表的罕见代字），取最右命中以剥离前置噪声
    best, best_start = "", -1
    for pat in _PATTERNS:
        mm = pat.search(s)
        if mm and mm.start() > best_start:
            best, best_start = mm.group(0), mm.start()
    return best


