"""doc_number.py —— 统一法规文号提取与规范化（五源共享，2026-09-05）

背景
----
五源（gov / mof / nfra / pbc / supp）此前各写各的文号提取正则与字段处理，
导致：半角方括号 ``[2026]`` 与全角六角括号 ``〔2026〕`` 混用、正文脏串被整段
吞入文号（如 ``金金金…财会〔2026〕12号``）、标题内嵌文号未回填、缺机构前缀等。

本模块吸收外部参考实现 ``UnifiedDocNumberExtractor`` 的 15 类优先级正则体系，
并修正其缺陷（1.12 正则错字符 ``〔\\d{4〕〕``、半角 [ ] 兼容），补充五源实际
前缀（金规/金办发/金办便函/银保监/保监中介/人身险部函/公开市场业务公告/财办等），
提供：
  - ``extract_doc_number(text)``   按优先级抽取首个文号（兼容全角/半角括号）
  - ``normalize_doc_number(v)``    规范化：半角 [] → 全角〔〕、压缩空白、去脏
  - ``extract_from_title(title)``  从标题抽取内嵌文号（《…》（文号）场景）
  - ``looks_like_doc_number(v)``   判定是否文号形态（供空值校验/补全触发）

规则口径（对照《党政机关公文处理工作条例》发文字号规范）
  发文字号 = 发文机关代字 + 〔年份〕 + 序号 + 号（如 银发〔1999〕407号）
  令 号   = 机关/机构名 + 令 + 第 N 号（如 中华人民共和国国务院令第300号）
本模块同时兼容半角 [ ] 输入并在 normalize 阶段统一为全角六角括号〔〕。
"""

