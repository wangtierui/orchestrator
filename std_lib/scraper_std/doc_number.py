def normalize_doc_number(v: object) -> str:
    """规范化文号：全/半角数字统一、半角 [] → 全角〔〕、压缩空白、
    截去头部标题/正文残渣、令号中文序号转阿拉伯。

    - '金规[2026]4号'                  → '金规〔2026〕4号'
    - '金金金…财会〔2026〕12号'         → '财会〔2026〕12号'（去头部单字重复）
    - '保险机构参与中国金融期货证监会公告〔2020〕12号' → '证监会公告〔2020〕12号'
      （2026-09-07：剥离前置标题残渣，仅保留「代字+〔年份〕序号号」真实片段）
    - '中华人民共和国主席令（第三十八号）' → '中华人民共和国主席令第38号'
      （2026-09-07：全角括号归一 + 令号中文序号转阿拉伯）
    - '国办发〔２０１３〕８７号'          → '国办发〔2013〕87号'
      （2026-09-07：全角数字归一）
    """
    if v is None:
        return ""
    s = str(v).strip()
    if not s:
        return ""
    # 1) 全角数字/括号 → 半角（修复全角数字与全角括号）
    s = s.translate(_FW_DIGITS).translate(_FW_PAREN)
    # 2) 空白压缩 + 半角 [] → 全角〔〕
    s = re.sub(r"\s+", " ", s)
    s = _HALF.sub(r"〔\1〕\2", s)  # [2026]N → 〔2026〕N
    s = s.replace("[", "〔").replace("]", "〕")
    # 3) 头部非中英文数字脏字清理
    s = re.sub(r"^[^\u4e00-\u9fa5A-Za-z0-9]+", "", s)
    # 4) 定位真实文号起点，丢弃前置标题/正文残渣（取最右合法片段）
    span = _locate_doc_span(s)
    if span:
        s = span
    # 5) 令号中文序号 → 阿拉伯（如 第三十八号 → 第38号）
    s = re.sub(
        r"令\s*[（(]?\s*(第?)\s*([一二三四五六七八九十百千两零\d]+)\s*号[）)]?",
        lambda m: "令" + ("第" if m.group(1) else "") + cn_to_arabic(m.group(2)) + "号",
        s,
    )
    # 6) 国务院令/主席令 官方全称补全（正式发文字号前缀为"中华人民共和国"）
    s = re.sub(r"(?<!中华人民共和国)国务院令", "中华人民共和国国务院令", s)
    s = re.sub(r"(?<!中华人民共和国)主席令", "中华人民共和国主席令", s)
    # 7) 文号年份/序号形态同化（2026-09-09 reconcile C2/legacy 漂移治理）：
    #    「〔YYYY〕第N号」≡「〔YYYY〕N号」≡「YYYY年第N号」≡「YYYY年N号」统一为
    #    「〔YYYY〕N号」——解决归属表(如 保监会令〔2013〕2号)与 clean(如 保监会令2013年第2号)
    #    表述差异造成的假漂移（legacy 163 中大批为同文号不同书写）。s 此时已剥标题/正文残渣。
    s = re.sub(r"(\d{4})\s*年\s*第?\s*(\d+)号", r"〔\1〕\2号", s)
    s = re.sub(r"〔(\d{4})〕\s*第?\s*(\d+)号", r"〔\1〕\2号", s)
    return clean_doc_number(s)


def clean_doc_number(s: str) -> str:
    """收尾清理：去尾部冗余、压缩内部空白、去首尾空白。"""
    s = s.strip()
    s = re.sub(r"\s+", "", s)
    # 截断到 '号'（避免吞入后续正文；允许保留闭合括号 ））] 等）
    idx = s.find("号")
    if idx > 0 and idx < len(s) - 1:
        tail = s[idx + 1 :]
        if tail and not tail[0].isdigit() and tail[0] not in "）)]":
            s = s[: idx + 1]
    return s


def extract_doc_number(text: str) -> str:
    """按优先级抽取首个文号；失败返回空串。兼容全角/半角括号输入。"""
    if not text:
        return ""
    s = str(text).strip()
    for pat in _PATTERNS:
        m = pat.search(s)
        if m:
            return normalize_doc_number(m.group(0))
    return ""


def extract_from_title(title: str) -> str:
    """从标题抽取内嵌文号。

    典型形态：『关于印发《XX办法》的通知（银发〔1999〕407号）』
              『XX规定（财政部令第116号）』『国务院令第300号』
    返回规范文号；无则空串。
    """
    if not title:
        return ""
    t = str(title).strip()
    # 优先括号内文号（标题尾部圆括号/六角括号内容）
    m = re.search(
        r"[（(]\s*([\u4e00-\u9fa5A-Za-z0-9〔〕\[\]第号、，,和与及\s]{4,60}?号)\s*[）)]", t
    )
    if m:
        dn = extract_doc_number(m.group(1))
        if dn:
            return dn
    # 标题整体直接抽取
    return extract_doc_number(t)


