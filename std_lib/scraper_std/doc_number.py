# 年份/序号统一
_FULL = re.compile(r"[\[(（]\s*(\d{4})\s*[\])）]")  # 任意括号内 4 位年
_HALF = re.compile(r"\[(\d{4})\]\s*(\d+)")  # [2026]123 半角

# 全角→半角：数字与括号（2026-09-07 修复 case 8 全角数字 ２０１３／８７）
_FW_DIGITS = str.maketrans("０１２３４５６７８９", "0123456789")
_FW_PAREN = str.maketrans("（）", "()")

# 令号中文序号 → 阿拉伯（2026-09-07 修复 case 5 主席令（第三十八号）→ 第38号）
_CN_DIGITS = {
    "零": 0,
    "一": 1,
    "二": 2,
    "两": 2,
    "三": 3,
    "四": 4,
    "五": 5,
    "六": 6,
    "七": 7,
    "八": 8,
    "九": 9,
}
_CN_UNITS = {"十": 10, "百": 100, "千": 1000}


def cn_to_arabic(s: str) -> str:
    """将中文序号（三十八/三百二十四/十）转为阿拉伯数字串；非中文序号原样返回。"""
    s = s.strip()
    if s.isdigit():
        return s
    total, section = 0, 0
    for ch in s:
        if ch in _CN_DIGITS:
            section = _CN_DIGITS[ch]
        elif ch in _CN_UNITS:
            unit = _CN_UNITS[ch]
            total += (section or 1) * unit
            section = 0
        else:
            return s  # 含非中文数字字符，放弃转换
    return str(total + section)


