"""生成 `requirements.lock`（方案 §13.2-1「依赖锁定」，零新工具链）。

口径：
  · `pip freeze` 全量快照（**含间接依赖** —— 锁的意义就是可复现整棵树）；
  · 剔除本地可编辑/路径条目（本仓自身）与 VCS 直连项（不可复现，须走 lock 条目）；
  · 头部写明生成命令与解释器/平台（锁的可复现性依赖这些上下文）；
  · 稳定排序 ⇒ 同环境重复生成 diff 为空（可入库、可评审）。

用法：python -m tools.gen_lock [--check]
  --check 只校验「lock 是否与当前环境一致」，不写盘（供门禁/ci_check 复用）。
"""
from __future__ import annotations

import argparse
import os
import platform
import subprocess
import sys
from datetime import datetime, timedelta, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCK = os.path.join(ROOT, "requirements.lock")

HEADER = """\
# requirements.lock -- pinned dependency tree (plan S13.2-1 / ADR-0011)
#
# GENERATED BY: python -m tools.gen_lock      (verify: --check)
# INTERPRETER:  {py} {ver} ({plat})
# ENTRIES:      full `pip freeze` snapshot (direct + transitive); local editable /
#               path / VCS entries removed (not reproducible, must be lock entries).
#
# WHY THIS FILE IS ASCII-ONLY (deliberate): lock files are machine-consumed by
# third-party tools (pip-audit reads them with the *locale* encoding; a UTF-8 file
# with CJK breaks under GBK/cp936 locales). Prose belongs in ADR-0011 / docs.
#
# RULES:
#   * This file is committed. Upgrading a dependency = a reviewable change to THIS
#     file (installing into the env without committing silently forks "the machine
#     that works" from "the locked machine" and destroys the CVE-scan baseline).
#   * Every new DIRECT dependency must first be registered in
#     `config/dependency_policy.yaml` with an ADR id or an explicit exemption note
#     (gate_dependency_audit D3 -- no shadow dependencies).
#   * CVE scan: `python -m pip_audit -r requirements.lock` (high/critical = FAIL).
#   * SBOM: CycloneDX is derived from this lock (`python -m tools.gen_sbom`), no
#     external generator required.
"""


def _freeze() -> list[str]:
    out = subprocess.run([sys.executable, "-m", "pip", "freeze", "--all"],
                         capture_output=True, text=True, encoding="utf-8",
                         errors="replace", cwd=ROOT)
    if out.returncode != 0:
        raise RuntimeError(f"pip freeze 失败 rc={out.returncode}: {out.stderr[:400]}")
    lines = [ln.strip() for ln in out.stdout.splitlines()]
    keep = []
    for ln in lines:
        if not ln or ln.startswith("#"):
            continue
        low = ln.lower()
        # 本仓自身（editable/路径）与 VCS 直连：不可复现/非 PyPI 分发
        if low.startswith("-e ") or low.startswith("file:") or " @ file:" in low \
                or low.startswith("-git") or "git+" in low:
            continue
        keep.append(ln)
    return sorted(keep, key=str.lower)


def render() -> str:
    head = HEADER.format(py=platform.python_implementation(), ver=platform.python_version(),
                         plat=f"{platform.system()} {platform.machine()}")
    return head + "\n".join(_freeze()) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验 lock 与当前环境一致")
    a = ap.parse_args()
    want = render()
    if a.check:
        if not os.path.exists(LOCK):
            print("[lock] 缺失 requirements.lock（运行 python -m tools.gen_lock）")
            return 1
        have = open(LOCK, encoding="utf-8").read()
        if _body(have) != _body(want):
            print("[lock] 与当前环境**不一致** —— 请运行 python -m tools.gen_lock 并提交变更")
            return 1
        print("[lock] 与当前环境一致")
        return 0
    with open(LOCK, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(want)
    n = len(_body(want).splitlines())
    print(f"[lock] 已写入 requirements.lock（{n} 条，{datetime.now(timezone(timedelta(hours=8))):%Y-%m-%d}）")
    return 0


def _body(text: str) -> str:
    """只比较条目区（头部含解释器版本/平台，允许跨机器差异）。"""
    return "\n".join(ln for ln in text.splitlines() if ln.strip() and not ln.startswith("#"))


if __name__ == "__main__":
    sys.exit(main())
