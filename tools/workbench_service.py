# -*- coding: utf-8 -*-
"""tools.workbench_service — 本地确认台的**开机自启动**安装/卸载/状态/验证。

为什么单独成工具（2026-10-21，第一百零六批 T3）
----------------------------------------------
用户要求"配置为开机自启动，并说明启动方式与验证方式"。若只在文档里写
"把快捷方式丢进 shell:startup"，有三个问题无法回答：
  1. 怎么**验证**它真的装上了？（需要 `status`）
  2. 装错了怎么**撤**？（需要 `uninstall`）
  3. 怎么保证**只有一个实例**？（需要 `--single-instance`）

方案选型（三种，按质量排序）
----------------------------
| 方案 | 需管理员 | 开机即启(免登录) | 失败重启 | 结论 |
|---|---|---|---|---|
| **计划任务（ONLOGON）** | 否（用户级） | 否（需登录） | 有限（靠单实例幂等兜） | **选用** |
| 启动文件夹快捷方式 | 否 | 否 | 无 | 备选（无 schtasks 时降级） |
| Windows 服务（nssm/sc.exe） | 是 | 是 | 有 | 不选：引入第三方依赖 + 提权 |

选计划任务的理由：**零提权**（用户级任务）、**可查询/可卸载**、**可延迟**
（避开开机 IO 高峰）、且不依赖第三方工具。代价是"需先登录"——对本地工作台
（单用户）完全可接受；若要"免登录启动"，须改用服务（需管理员 + 第三方）。

可靠性设计
----------
* **单实例**：启动参数带 `--single-instance`（`fs_lock.ProcessLock`）。
  计划任务每次登录都会触发，没有它就会起多个进程互相踩踏。
* **日志落盘**：`--log-file`（无控制台时唯一可查），`RotatingFileHandler` 5MB×3。
* **无窗口**：用 `pythonw.exe`（否则每次登录都弹一个黑框）。
* **包装器 .cmd**：`schtasks /TR` 有命令长度限制，且需要 `cd` 到仓根
  （`cli.py` 依赖 cwd）⇒ 用一个 .cmd 包住，`/TR` 只指向它。
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
import urllib.error
import urllib.request

from bootstrap import bootstrap

bootstrap("all")

import paths
from config.exitcodes import ExitCode

#: 计划任务名（`schtasks /TN`）
TASK_NAME = "WorkBuddyRegulatoryConsole"

#: 包装器与日志的落点（都在 `data/state/` 下，随仓库走）
START_CMD = os.path.join(paths.DATA_DIR, "state", "workbench_start.cmd")
LOG_FILE = os.path.join(paths.DATA_DIR, "state", "workbench.log")
PID_FILE = os.path.join(paths.DATA_DIR, "state", "workbench.lock")

#: 默认端口（与 `web.DEFAULT_PORT` 一致；被占用时会递增）
DEFAULT_PORT = 8765


def _pythonw() -> str:
    """`pythonw.exe` 的绝对路径（无窗口运行；找不到则退回 `python`）。"""
    exe = sys.executable
    cand = os.path.join(os.path.dirname(exe), "pythonw.exe")
    return cand if os.path.exists(cand) else exe


def _write_start_cmd(port: int = DEFAULT_PORT, lan: bool = True) -> str:
    """生成启动包装器（**幂等**：内容确定则不改写，保留 mtime 便于判断）。

    ⚠️ **本文件必须是纯 ASCII（纯英文注释）** —— 这是 2026-10-21 蓝屏后重启
    实测到的真实故障：包装器原用 UTF-8 写中文注释，而 `cmd.exe` 按系统代码页
    （简体中文为 **CP936/GBK**）读取 ⇒ 中文变成乱码，其中部分字节被解释为
    命令分隔符，`rem` 注释行被截断、后半段当成命令执行，登录后弹出：

        '氭寔涔咃細閲嶈窇' 不是内部或外部命令，也不是可运行的程序或批处理文件。

    （`氭寔涔咃細閲嶈窇` 就是 UTF-8 的「…持久：重跑」被 GBK 解码后的残片。）

    修法：注释全部英文 + 写入时用 `encoding="ascii"`（**若混入任何非 ASCII
    字节会立刻抛错**，从根上防止回归）。中文说明放在 README §6.6 与本 docstring。
    """
    repo = paths.ROOT
    state_dir = os.path.dirname(LOG_FILE)
    lines = [
        "@echo off",
        "rem WorkBuddy local console - auto-start wrapper.",
        "rem GENERATED by tools/workbench_service.py; rerun 'install' to rewrite.",
        "rem ASCII-ONLY on purpose: cmd.exe reads .cmd in the OEM codepage (CP936),",
        "rem so UTF-8 Chinese comments get garbled and can break the script.",
        "cd /d %s" % repo,
        'if not exist "%s" mkdir "%s"' % (state_dir, state_dir),
        '"%s" cli.py serve %s --port %d ^' % (
            _pythonw(), "--lan" if lan else "--host 127.0.0.1", port),
        '  --single-instance --pid-file "%s" --log-file "%s"' % (PID_FILE,
                                                                 LOG_FILE),
    ]
    body = "\r\n".join(lines) + "\r\n"
    os.makedirs(state_dir, exist_ok=True)
    if os.path.exists(START_CMD):
        old = io_open(START_CMD)
        if old.replace("\r\n", "\n") == body.replace("\r\n", "\n"):
            return START_CMD      # 内容一致 ⇒ 不动（保持 mtime）
    # `encoding="ascii"` 是**刻意的**：非 ASCII 会抛 UnicodeEncodeError
    io_write(START_CMD, body, encoding="ascii")
    return START_CMD


def io_open(p: str) -> str:
    with open(p, encoding="utf-8", errors="replace") as fh:
        return fh.read()


def io_write(p: str, text: str, encoding: str = "utf-8") -> None:
    """写文本文件（`newline=""` 保留调用方给的换行：`.cmd` 必须是 CRLF）。

    `encoding` 可指定为 `"ascii"` —— `.cmd` 用它可以从根上阻止非 ASCII 混入
    （否则 cmd.exe 按 OEM 代码页读取会乱码，实测导致登录时命令行报错）。
    """
    with open(p, "w", encoding=encoding, newline="") as fh:
        fh.write(text)


def _schtasks(*args: str) -> tuple[int, str]:
    """跑 `schtasks`，返回 (rc, 输出)。"""
    cmd = ["schtasks", *args]
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=60)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def _is_windows() -> bool:
    return os.name == "nt"


def install(*, port: int = DEFAULT_PORT, delay: int = 30, lan: bool = True) -> int:
    """安装开机自启动（计划任务 ONLOGON，用户级、**不需管理员**）。

    `delay`：登录后延迟多少秒再启动（避开开机 IO 高峰；`schtasks` 的
    `/DELAY` 只支持 ONSTART/ONLOGON 触发器，格式 `HHMM` 或 `mm:ss`）。

    `lan`：是否对公司内网开放（默认 True，2026-10-23 起）。
    **只开放只读能力**；待办处置/留言处置/本地文件/宿主诊断/提交详情
    仍由 `web/policy` 按来源 IP 拒绝（不是靠前端隐藏）。
    如需只让本机用，`install --local`。
    """
    if not _is_windows():
        sys.stderr.write(
            "本工具仅支持 Windows（计划任务）。Linux/macOS 请用 launchd/systemd。\n")
        return ExitCode.ENV
    cmd_path = _write_start_cmd(port=port, lan=lan)
    trig = "ONLOGON"
    args = [
        "/Create", "/TN", TASK_NAME, "/SC", trig,
        "/TR", f'cmd /c "{cmd_path}"',
        "/RL", "LIMITED",      # 用户级最小权限（**不需要管理员**）
        "/F",                  # 覆盖同名任务（幂等安装）
    ]
    if delay:
        # 延迟启动。⚠️ `schtasks /DELAY` 的格式是 **`mmmm:ss`（分钟:秒）**，
        # 不是 `HHMM` —— 写成 HHMM 会报「值无效（应该是 mmmm:ss 格式）」
        # （rc=2147500037，实测踩到）。上限 2147483647 分钟。
        minutes, seconds = divmod(int(delay), 60)
        if seconds > 59:            # 防御：秒必须 < 60
            minutes += seconds // 60
            seconds = seconds % 60
        args += ["/DELAY", f"{minutes:04d}:{seconds:02d}"]
    rc, out = _schtasks(*args)
    if rc != 0:
        sys.stderr.write(f"[install] schtasks 失败（rc={rc}）：\n{out}\n")
        return ExitCode.OK if rc == 0 else ExitCode.FAIL
    print(f"[install] 计划任务已创建：{TASK_NAME}")
    print(f"  触发器  ：{trig}" + (f"（延迟 {delay}s）" if delay else ""))
    print(f"  动作    ：cmd /c {cmd_path}")
    print("  权限    ：LIMITED（当前用户，**无需管理员**）")
    print("  启动方式：下次登录时自动运行；也可手动执行")
    print(f"            schtasks /Run /TN {TASK_NAME}")
    print("  验证方式：python -m tools.workbench_service status")
    print("            python -m tools.workbench_service verify")
    if lan:
        from web.policy import lan_ipv4

        print("  访问范围：**公司内网只读**（待办处置/留言处置/本地文件/宿主诊断/"
              "提交详情仍仅限本机）")
        for ip in lan_ipv4():
            print(f"            内网地址 http://{ip}:{port}/")
        print("  ⚠️ 若同事打不开：多为 Windows 防火墙未放行该端口（见 README §6.8）")
    else:
        print("  访问范围：仅本机（127.0.0.1）")
    return ExitCode.OK


def uninstall() -> int:
    """卸载（删除计划任务）。**不动**数据目录里的 cmd/日志（可留作排查）。"""
    if not _is_windows():
        sys.stderr.write("仅支持 Windows。\n")
        return ExitCode.ENV
    rc, out = _schtasks("/Delete", "/TN", TASK_NAME, "/F")
    if rc != 0:
        if "找不到" in out or "does not exist" in out.lower():
            print(f"[uninstall] 任务 {TASK_NAME} 本就不存在（无需卸载）")
            return ExitCode.OK
        sys.stderr.write(f"[uninstall] schtasks 失败（rc={rc}）：\n{out}\n")
        return ExitCode.OK if rc == 0 else ExitCode.FAIL
    print(f"[uninstall] 计划任务已删除：{TASK_NAME}")
    print(f"  保留（未删）：{START_CMD}")
    print(f"              {LOG_FILE}")
    return ExitCode.OK


def _task_exists() -> bool:
    rc, out = _schtasks("/Query", "/TN", TASK_NAME, "/FO", "LIST")
    return rc == 0 and TASK_NAME in out


def _proc_running() -> tuple[bool, str]:
    """确认台进程是否在跑（读单实例锁里的 PID + 存活校验）。"""
    from std_lib.common_lib import fs_lock

    pid = fs_lock._read_lock_pid(PID_FILE) if os.path.exists(PID_FILE) else None
    if pid is None:
        return False, "无锁文件（未启动过，或已退出）"
    alive = fs_lock._pid_alive(pid)
    return alive, f"pid={pid} {'存活' if alive else '已退出（陈旧锁）'}"


def _health_ok(port: int = DEFAULT_PORT) -> tuple[bool, str]:
    """探活：`/api/health` 200 + JSON 含 ok/available；**401 也算"活着"**。

    ⚠️ 2026-10-23：认证上线后，未带凭据的探活会拿到 **401**。原实现只认 200
    ⇒ `status`/`verify` 会把**健康的**服务报成"不通"，计划任务自检也跟着误判
    （实测：进程存活、内网可登录，而 `status` 说"8765~8784 均无响应"）。
    401 恰恰证明"HTTP 服务在跑、只是要登录"，应判为可达并标注需要认证。
    """
    for p in range(port, port + 20):
        url = f"http://127.0.0.1:{p}/api/health"
        try:
            with urllib.request.urlopen(url, timeout=3) as r:
                if r.status != 200:
                    continue
                import json
                d = json.loads(r.read().decode("utf-8", "replace"))
                if isinstance(d, dict) and ("ok" in d or "available" in d):
                    return True, f"{url} → 200"
        except urllib.error.HTTPError as e:
            if e.code in (401, 403):
                return True, f"{url} → {e.code}（服务在跑，需登录）"
            continue
        except Exception:  # noqa: BLE001  端口未监听就换下一个
            continue
    return False, f"127.0.0.1:{port}~{port + 19} 均无响应"


def status(*, port: int = DEFAULT_PORT) -> int:
    """打印三项状态：计划任务 / 进程 / 健康探活。"""
    rows = []
    if _is_windows():
        rows.append(("计划任务", "已安装" if _task_exists() else "**未安装**",
                     TASK_NAME))
    running, why = _proc_running()
    rows.append(("进程", "在跑" if running else "**未运行**", why))
    ok, hwhy = _health_ok(port)
    rows.append(("健康", "通" if ok else "**不通**", hwhy))
    rows.append(("日志", "有" if os.path.exists(LOG_FILE) else "无", LOG_FILE))
    w = max(len(a) for a, _, _ in rows)
    print("=" * (w + 52))
    for a, b, c in rows:
        print(f"  {a:<{w}}  {b:<10}  {c}")
    print("=" * (w + 52))
    all_ok = all("**" not in b for _, b, _ in rows)
    print("结论：" + ("就绪（开机自启动可用）" if all_ok else "未就绪（见上行 ** 项）"))
    return ExitCode.OK if all_ok else ExitCode.FAIL


def verify(*, port: int = DEFAULT_PORT, wait: int = 20) -> int:
    """安装后自检：若服务未起，**先手动触发一次计划任务**再等 `wait` 秒探活。

    这比"让用户重启验证"可靠得多：装完立刻可验证成败。
    """
    if not _is_windows():
        sys.stderr.write("仅支持 Windows。\n")
        return ExitCode.ENV
    if not _task_exists():
        sys.stderr.write(f"[verify] 计划任务 {TASK_NAME} 不存在（先 install）\n")
        return ExitCode.FAIL
    ok, why = _health_ok(port)
    if ok:
        print(f"[verify] 服务已在运行：{why}")
        print("[verify] 通过 ✓")
        return ExitCode.OK
    print("[verify] 尚未监听 ⇒ 手动触发一次任务（schtasks /Run）…")
    rc, out = _schtasks("/Run", "/TN", TASK_NAME)
    if rc != 0:
        sys.stderr.write(f"[verify] 触发失败（rc={rc}）：\n{out}\n")
        return ExitCode.OK if rc == 0 else ExitCode.FAIL
    deadline = time.time() + max(5, wait)
    while time.time() < deadline:
        time.sleep(1.0)
        ok, why = _health_ok(port)
        if ok:
            print(f"[verify] 已就绪：{why}")
            print(f"[verify] 日志：{LOG_FILE}")
            print("[verify] 通过 ✓")
            return ExitCode.OK
    sys.stderr.write(f"[verify] {wait}s 内未就绪 ⇒ 失败。\n"
                     f"请查日志：{LOG_FILE}\n")
    return ExitCode.FAIL


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="workbench_service",
        description="本地确认台开机自启动：install / uninstall / status / verify")
    ap.add_argument("action", choices=["install", "uninstall", "status",
                                       "verify"])
    ap.add_argument("--port", type=int, default=DEFAULT_PORT,
                    help=f"确认台端口（默认 {DEFAULT_PORT}；占用时自动递增）")
    ap.add_argument("--delay", type=int, default=30,
                    help="登录后延迟多少秒启动（默认 30，避开开机 IO 高峰）")
    ap.add_argument("--wait", type=int, default=20,
                    help="verify 时最长等待秒数（默认 20）")
    ap.add_argument("--local", action="store_true",
                    help="install 时**只绑 127.0.0.1**（默认对公司内网开放只读；"
                         "详见 web/policy.py 的分级策略）")
    a = ap.parse_args(argv)

    if a.action == "install":
        return install(port=a.port, delay=a.delay, lan=not a.local)
    if a.action == "uninstall":
        return uninstall()
    if a.action == "status":
        return status(port=a.port)
    return verify(port=a.port, wait=a.wait)


if __name__ == "__main__":
    raise SystemExit(main())
